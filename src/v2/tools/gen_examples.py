#!/usr/bin/env python3
"""Regenerate web/examples.json from examples/*.c.

The example kernels have exactly one home: `examples/`. The CLI reads them from
there, the tests run them from there, and this puts the same text in front of
the page. Nothing about an example is written twice, and nothing about its
*result* is written down at all — the numbers appear when you press Compile,
because that is the only place they can be true.

    python3 tools/gen_examples.py [--check]
"""

import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXAMPLES = os.path.join(ROOT, 'examples')
OUTPUT = os.path.join(ROOT, 'web', 'examples.json')

# The first prose line of the leading block comment describes the kernel.
# Lines naming a physical form are documentation for a reader of the file, not
# something the page should assert before the solver has run.
_COMMENT = re.compile(r'/\*(.*?)\*/', re.S)


def summarize(source):
    match = _COMMENT.search(source)
    if not match:
        return ''
    for raw in match.group(1).splitlines():
        line = raw.strip().lstrip('*').strip()
        if line:
            return line
    return ''


def collect():
    out = []
    for name in sorted(os.listdir(EXAMPLES)):
        if not name.endswith('.c'):
            continue
        path = os.path.join(EXAMPLES, name)
        with open(path) as handle:
            source = handle.read()
        out.append({
            'name': name[:-2],
            'file': name,
            'summary': summarize(source),
            'source': source,
        })
    return out


def build():
    return {
        'note': 'generated by tools/gen_examples.py from examples/*.c; do not '
                'edit by hand',
        'examples': collect(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true',
                        help='exit non-zero if the file is stale')
    args = parser.parse_args()

    wanted = build()
    current = None
    if os.path.exists(OUTPUT):
        with open(OUTPUT) as handle:
            current = json.load(handle)

    if current == wanted:
        print('examples.json is up to date (%d examples)'
              % len(wanted['examples']))
        return 0
    if args.check:
        print('examples.json is stale; run: python3 tools/gen_examples.py',
              file=sys.stderr)
        return 1

    with open(OUTPUT, 'w') as handle:
        json.dump(wanted, handle, indent=2)
        handle.write('\n')
    print('wrote %s (%d examples)' % (OUTPUT, len(wanted['examples'])))
    return 0


if __name__ == '__main__':
    sys.exit(main())
