#!/usr/bin/env python3
"""Regenerate web/qm-manifest.json.

The worker installs the engine into Pyodide by fetching exactly the files listed
here.  `tests/test_manifest.py` fails if the list drifts from what is on disk, so
a new module can never be silently missing in the browser while the tests pass
locally.

    python3 tools/gen_manifest.py [--check]
"""

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACKAGE = os.path.join(ROOT, 'qm')
MANIFEST = os.path.join(ROOT, 'web', 'qm-manifest.json')
BASE = '..'


def collect():
    files = []
    for dirpath, dirnames, filenames in os.walk(PACKAGE):
        dirnames[:] = sorted(d for d in dirnames if d != '__pycache__')
        for name in sorted(filenames):
            if not name.endswith('.py'):
                continue
            path = os.path.join(dirpath, name)
            files.append(os.path.relpath(path, ROOT).replace(os.sep, '/'))
    return sorted(files)


def build():
    return {
        'base': BASE,
        'entry': 'qm.browser',
        'files': collect(),
        'note': 'generated by tools/gen_manifest.py; run it after adding a '
                'module to the qm package',
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true',
                        help='exit non-zero if the manifest is stale')
    args = parser.parse_args()

    wanted = build()
    current = None
    if os.path.exists(MANIFEST):
        with open(MANIFEST) as handle:
            current = json.load(handle)

    if current == wanted:
        print('manifest is up to date (%d files)' % len(wanted['files']))
        return 0
    if args.check:
        print('manifest is stale; run: python3 tools/gen_manifest.py',
              file=sys.stderr)
        return 1

    with open(MANIFEST, 'w') as handle:
        json.dump(wanted, handle, indent=2)
        handle.write('\n')
    print('wrote %s (%d files)' % (MANIFEST, len(wanted['files'])))
    return 0


if __name__ == '__main__':
    sys.exit(main())
