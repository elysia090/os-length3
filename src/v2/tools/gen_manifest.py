#!/usr/bin/env python3
"""Regenerate the ordinary and Linux browser-worker manifests.

The worker installs the engine into Pyodide by fetching exactly the files listed
here.  `tests/test_manifest.py` fails if the list drifts from what is on disk, so
a new module can never be silently missing in the browser while the tests pass
locally.

    python3 tools/gen_manifest.py [--check]
"""

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Both packages run in the browser: QM produces the minimized wasm32 sequence,
# and the VM package compiles it into the executable artifact.
PACKAGES = ('qm', 'vm')
KERNEL_PACKAGES = ('qm', 'kernel')
# The C and its build script are not importable and are not shipped.  The
# compiled module is opened only through the repository artifact catalog.
SKIP_DIRS = ('__pycache__', 'wasm', 'guest')
MANIFEST = os.path.join(ROOT, 'web', 'qm-manifest.json')
KERNEL_MANIFEST = os.path.join(ROOT, 'web', 'kernel-manifest.json')
KERNEL_SKIP_FILES = ('kernel/run.py',)
BASE = '..'


def collect(packages=PACKAGES, skip_files=()):
    files = []
    skipped = set(skip_files)
    for package in packages:
        for dirpath, dirnames, filenames in os.walk(os.path.join(ROOT, package)):
            dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
            for name in sorted(filenames):
                if not name.endswith('.py'):
                    continue
                path = os.path.join(dirpath, name)
                relative = os.path.relpath(path, ROOT).replace(os.sep, '/')
                if relative not in skipped:
                    files.append(relative)
    return sorted(files)


def build():
    return {
        'base': BASE,
        'entry': 'qm.browser',
        'files': collect(),
        'note': 'generated by tools/gen_manifest.py; run it after adding a '
                'module to the qm or vm package',
    }


def build_kernel():
    return {
        'base': BASE,
        'entry': 'kernel.browser',
        'files': collect(KERNEL_PACKAGES, KERNEL_SKIP_FILES),
        'note': 'generated by tools/gen_manifest.py; Linux runs in a separate '
                'disposable worker',
    }


def _update(path, wanted, check):
    current = None
    if os.path.exists(path):
        with open(path) as handle:
            current = json.load(handle)
    if current == wanted:
        print('%s is up to date (%d files)'
              % (os.path.basename(path), len(wanted['files'])))
        return True
    if check:
        print('%s is stale; run: python3 tools/gen_manifest.py'
              % os.path.basename(path), file=sys.stderr)
        return False
    with open(path, 'w', newline='\n') as handle:
        json.dump(wanted, handle, indent=2)
        handle.write('\n')
    print('wrote %s (%d files)' % (path, len(wanted['files'])))
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true',
                        help='exit non-zero if the manifest is stale')
    args = parser.parse_args()

    ok = _update(MANIFEST, build(), args.check)
    ok = _update(KERNEL_MANIFEST, build_kernel(), args.check) and ok
    return 0 if ok else 1


if __name__ == '__main__':
    sys.exit(main())
