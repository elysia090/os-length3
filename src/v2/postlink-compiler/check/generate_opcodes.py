#!/usr/bin/env python3
"""Generate include/postlink/opcodes.h from qm.steppage.

The C side sees opcodes as the byte the template stores, but the composition
rules are written against op *names*: `op.startswith('memory.')` decides whether
a node joins the memory ordering chain, and two frozensets decide whether a
projection is already published or has to be materialized.  Those predicates are
not ranges -- memory.* occupies six disjoint runs of the table, and
memory.i64.load_region sits outside the MEMORY_OPS block entirely -- so the
tables are generated rather than transcribed.

    python3 check/generate_opcodes.py            write the header
    python3 check/generate_opcodes.py --check    fail if it is stale
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from qm.steppage import (FLAG_PROJECTION_OPS, MEMORY_SCALE_MASK,
                         MEMORY_SCALE_SHIFT, MEMORY_SHAPE_MASK,
                         MEMORY_VIRTUAL64, OPS,
                         REGION_PROJECTION_OPS)

TARGET = (Path(__file__).resolve().parents[1]
          / 'include' / 'postlink' / 'opcodes.h')


def bitmap(indices, count):
    words = [0] * ((count + 63) // 64)
    for index in indices:
        words[index // 64] |= 1 << (index % 64)
    return words


def render():
    count = len(OPS)
    OP_INDEX = set(OPS)
    memory = [i for i, name in enumerate(OPS) if name.startswith('memory.')]
    # _compact_once keeps these alive whatever reads them, because the trap is
    # observable in itself.  The reference tests the name after the first dot.
    traps = frozenset(('DIV_S', 'DIV_U', 'REM_S', 'REM_U'))
    trapping = [i for i, name in enumerate(OPS)
                if name.split('.', 1)[-1] in traps]
    flags = sorted(OPS.index(name) for name in FLAG_PROJECTION_OPS)
    region = sorted(OPS.index(name) for name in REGION_PROJECTION_OPS)
    published = sorted(set(flags) | set(region))
    # _rebase_overwritten_flags walks the flag chain through these.
    producers = sorted(OPS.index(name) for name in (
        'lane64.X86_FLAGS', 'lane64.X86_ALU', 'lane64.X86_AFFINE_ALU',
        'lane64.X86_COMPARE', 'lane64.X86_TEST', 'lane64.X86_SHIFT_FLAGS',
        'lane64.X86_MUL_FLAGS', 'lane64.X86_BIT_FLAGS'))
    named = ('lane64.X86_FLAGS', 'lane64.X86_ALU', 'lane64.X86_AFFINE_ALU',
             'lane64.X86_COMPARE', 'lane64.X86_TEST',
             'lane64.X86_SHIFT_FLAGS', 'memory.i64.pre_store',
             'memory.i64.load', 'memory.i64.load_region', 'lane64.ADD',
             'lane64.X86_CONDITION')

    lines = [
        '/* Generated by check/generate_opcodes.py.  Do not edit.',
        ' *',
        ' * The composition rules in qm/stepnormalize.py test op names, and a',
        ' * template stores opcodes.  These bitmaps carry the two predicates a',
        ' * composer needs: whether a node joins the memory ordering chain, and',
        ' * whether a projection is already published by its source and so needs',
        ' * no materialized node.',
        ' *',
        ' * Neither is a range.  memory.* occupies six disjoint runs, and',
        ' * memory.i64.load_region is at %d, outside the MEMORY_OPS block.'
        % region[0],
        ' */',
        '',
        '#ifndef POSTLINK_OPCODES_H',
        '#define POSTLINK_OPCODES_H',
        '',
        '#include <postlink/format.h>',
        '',
        '#define PL_OPCODE_COUNT %du' % count,
        '/* The memory access shape, as decode_memory_shape reads it. */',
        '#define PL_MEMORY_SHAPE_SCALE_SHIFT %du' % MEMORY_SCALE_SHIFT,
        '#define PL_MEMORY_SHAPE_SCALE_MASK 0x%xu' % MEMORY_SCALE_MASK,
        '#define PL_MEMORY_SHAPE_VIRTUAL64 0x%xu' % MEMORY_VIRTUAL64,
        '#define PL_MEMORY_SHAPE_MASK 0x%xu' % MEMORY_SHAPE_MASK,
        '',
        '#define PL_OPCODE_RELATIVE_RESULT %du'
        % OPS.index('memory.i64.relative_result'),
        '',
    ]
    for name in named:
        # lane64.X86_ALU becomes X86_ALU; memory.i64.pre_store becomes
        # MEMORY_PRE_STORE, since a dot is not an identifier.
        parts = name.split('.')
        macro = (parts[-1].upper() if parts[0].startswith('lane')
                 else '%s_%s' % (parts[0].upper(), parts[-1].upper()))
        lines.append('#define PL_OPCODE_%s %du' % (macro, OPS.index(name)))
    lines.append('')

    def emit(name, indices, comment):
        lines.append('/* %s */' % comment)
        lines.append('static const pl_u64 %s[] = {' % name)
        for word in bitmap(indices, count):
            lines.append('    0x%016xull,' % word)
        lines.append('};')
        lines.append('')

    emit('PL_OPCODE_MEMORY', memory,
         'op.startswith("memory.") -- %d opcodes' % len(memory))
    # _reopen_load_regions picks its load by (bits, width, signed), so the
    # table is generated rather than a name built at runtime.
    region = []
    for bits in (32, 64):
        for width in (1, 2, 4, 8):
            for signed in (0, 1):
                natural = bits // 8
                suffix = ('' if width == natural
                          else '%d_%s' % (width * 8, 's' if signed else 'u'))
                name = 'memory.i%d.load%s' % (bits, suffix)
                region.append((bits, width, signed,
                               OPS.index(name) if name in OP_INDEX else -1))
    lines.append('/* memory.i{bits}.load{suffix} by (bits, width, signed);')
    lines.append(' * 255 where the reference would name no such load. */')
    lines.append('static const pl_u8 PL_OPCODE_REGION_LOAD[2][9][2] = {')
    for bits in (32, 64):
        lines.append('    { /* i%d */' % bits)
        for width in range(9):
            entry = [next((code for b, w, s, code in region
                           if b == bits and w == width and s == signed), -1)
                     for signed in (0, 1)]
            lines.append('        { %s, %s },'
                         % tuple('%du' % code if code >= 0 else '255u'
                                 for code in entry))
        lines.append('    },')
    lines.append('};')
    lines.append('')

    # The arithmetic laneops.select chooses for _reopen_consumed_x86_alu.  It
    # takes the immediate form when either side is constant -- swapping the
    # arguments when it is the left one, which subtraction cannot do -- and the
    # register form otherwise.  Width matters only through i32 versus i64.
    semantics = ('and', 'add', 'sub', 'or', 'xor')
    immediate = ('AND', 'ADD', 'SUB', 'OR', 'XOR')
    register = ('ANDR', 'ADDR', 'SUBR', 'ORR', 'XORR')
    lines.append('/* laneops.select, arithmetic only: [i32?][and add sub or xor] */')
    for label, table in (('IMMEDIATE', immediate), ('REGISTER', register)):
        lines.append('static const pl_u8 PL_OPCODE_ALU_%s[2][5] = {' % label)
        for lane in ('lane32', 'lane64'):
            row = ['%du' % OPS.index('%s.%s' % (lane, name)) for name in table]
            lines.append('    { %s },' % ', '.join(row))
        lines.append('};')
        lines.append('')
    lines.append('/* Carry-in add, by lane width; 255 where none exists. */')
    lines.append('static const pl_u8 PL_OPCODE_ADD3[2] = { %du, %du };'
                 % (OPS.index('lane32.ADD3'), OPS.index('lane64.ADD3')))
    lines.append('')

    emit('PL_OPCODE_FLAG_PRODUCER', producers,
         'the flag chain _rebase_overwritten_flags walks -- %d opcodes'
         % len(producers))
    emit('PL_OPCODE_TRAPPING', trapping,
         'the divides whose trap is observable -- %d opcodes' % len(trapping))
    emit('PL_OPCODE_PUBLISHED_PROJECTION', published,
         'FLAG_PROJECTION_OPS | REGION_PROJECTION_OPS -- %d opcodes'
         % len(published))

    lines.extend([
        'static inline int pl_opcode_in(const pl_u64 *set, pl_u32 opcode)',
        '{',
        '    if (opcode >= PL_OPCODE_COUNT) return 0;',
        '    return (int)((set[opcode >> 6] >> (opcode & 63u)) & 1u);',
        '}',
        '',
        '#define pl_opcode_is_memory(op) pl_opcode_in(PL_OPCODE_MEMORY, (op))',
        '#define pl_opcode_traps(op) pl_opcode_in(PL_OPCODE_TRAPPING, (op))',
        '#define pl_opcode_produces_flags(op) '
        'pl_opcode_in(PL_OPCODE_FLAG_PRODUCER, (op))',
        '#define pl_opcode_publishes_projection(op) '
        'pl_opcode_in(PL_OPCODE_PUBLISHED_PROJECTION, (op))',
        '',
        '#endif /* POSTLINK_OPCODES_H */',
        '',
    ])
    return '\n'.join(lines)


def main():
    text = render()
    if '--check' in sys.argv:
        if not TARGET.exists() or TARGET.read_text(encoding='utf-8') != text:
            raise SystemExit('opcodes.h is stale; regenerate it')
        print('opcodes.h matches qm.steppage')
        return 0
    TARGET.write_text(text, encoding='utf-8', newline='\n')
    print('wrote %s' % TARGET.name)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
