/* Canonical GNU ar view generated from shared immutable member payloads. */

#ifndef ARTIFACT_ARCHIVE_H
#define ARTIFACT_ARCHIVE_H

#include <artifact/payload.h>

#define ARTIFACT_ERROR_ARCHIVE       (-74)
#define ARTIFACT_ERROR_ARCHIVE_RANGE (-75)

typedef struct {
    const pl_u8 *name;
    pl_u32 name_bytes;
    pl_u32 mode;
    const pl_u8 *payload;
    pl_u32 payload_bytes;
} artifact_archive_member;

typedef struct {
    const pl_u8 *name;
    pl_u32 name_bytes;
    pl_u32 member_rank;
} artifact_archive_symbol;

typedef struct {
    const artifact_archive_member *members;
    pl_u32 member_count;
    const artifact_archive_symbol *symbols;
    pl_u32 symbol_count;
} artifact_archive_view;

typedef struct {
    artifact_archive_member *members;
    artifact_archive_symbol *symbols;
    /* Canonical member header coordinates are strictly increasing.  They are
     * construction-only and let symbol offsets reopen member ranks by binary
     * search instead of a symbol-by-member scan. */
    pl_u32 *member_header;
    pl_u32 member_capacity;
    pl_u32 symbol_capacity;
} artifact_archive_read_workspace;

/* Open the canonical GNU ar grammar owned by this product.  Names and payloads
 * in the returned view borrow `source`; no archive stream or copied member
 * payload becomes a second owner. */
int artifact_archive_read_measure(
    const pl_u8 *source, pl_u32 source_bytes,
    pl_u32 *members, pl_u32 *symbols);
int artifact_archive_read(
    const pl_u8 *source, pl_u32 source_bytes,
    const artifact_archive_read_workspace *workspace,
    artifact_archive_view *out);

typedef struct {
    pl_u64 *member_header;
    pl_u32 *long_name_offset;
    pl_u32 member_capacity;
} artifact_archive_workspace;

typedef struct {
    pl_u32 members;
    pl_u32 symbols;
    pl_u64 payload_occurrence_bytes;
    pl_u64 generated_stream_bytes;
    pl_u64 archive_bytes;
    pl_u32 long_name_bytes;
    pl_u32 symbol_index_bytes;
} artifact_archive_projection;

/* Member payload ranks are generated by artifact_share_project from exact
 * immutable bytes before this view is built.  Names, modes, member order and
 * symbol resolution remain observable view fields.  Every byte of the ar
 * header, name table, symbol table, alignment and member coordinate is then a
 * total function of those fields and is not stored as a second payload. */
int artifact_archive_project(const artifact_archive_view *view,
                             const artifact_archive_workspace *workspace,
                             artifact_archive_projection *out);
int artifact_archive_write(const artifact_archive_view *view,
                           const artifact_archive_workspace *workspace,
                           pl_u8 *target, pl_u32 target_capacity,
                           pl_u32 *written);

/* Irreducible observable archive-view rows. Member payload identity is not
 * duplicated here: flattened member coordinate -> payload occurrence -> rank
 * is generated by the enclosing complete projection. */
int artifact_archive_member_material_write(
    const artifact_archive_member *member,
    pl_u8 *target, pl_u32 capacity, pl_u32 *written);
int artifact_archive_symbol_material_write(
    const artifact_archive_symbol *symbol,
    pl_u8 *target, pl_u32 capacity, pl_u32 *written);

/* Exact public responses used by the semantic completeness gate. These
 * include member payload bytes, unlike the minimal stored ARVM1 view row. */
int artifact_archive_member_response_write(
    const artifact_archive_member *member,
    pl_u8 *target, pl_u32 capacity, pl_u32 *written);
int artifact_archive_symbol_response_write(
    const artifact_archive_symbol *symbol,
    pl_u8 *target, pl_u32 capacity, pl_u32 *written);

/* Prove that every archive member resolves through the global immutable
 * payload population. `member_occurrence[i]` identifies the occurrence owned
 * by member i; its rank is generated and is not retained in the view. */
int artifact_archive_verify_payload_ranks(
    const artifact_archive_view *view,
    const artifact_payload *global_payloads, pl_u32 payload_occurrences,
    const pl_u32 *member_occurrence,
    const artifact_payload_workspace *payload_workspace,
    const artifact_payload_projection *payload_projection);

typedef struct {
    artifact_archive_view view;
    const pl_u32 *member_payload_occurrence;
    const pl_u8 *canonical_bytes;
    pl_u32 canonical_byte_count;
} artifact_archive_instance;

typedef struct {
    artifact_payload_workspace payload;
    pl_u64 *member_header;
    pl_u32 *long_name_offset;
    pl_u32 member_capacity;
    pl_u8 *generated;
    pl_u32 generated_capacity;
} artifact_archive_complete_workspace;

typedef struct {
    artifact_payload_projection payload;
    pl_u32 archives;
    pl_u32 members;
    pl_u32 symbols;
    pl_u64 opened_archive_bytes;
    pl_u64 generated_archive_bytes;
    pl_u64 removed_archive_bytes;
} artifact_archive_complete_projection;

/* Reopen every canonical archive byte from its observable view and the one
 * global immutable-payload quotient.  Success proves both that every member
 * points at its necessary exact payload rank and that no serialized archive
 * stream is a necessary second owner. */
int artifact_archive_complete_project(
    const artifact_archive_instance *archives, pl_u32 archive_count,
    const artifact_payload *global_payloads, pl_u32 payload_occurrences,
    const artifact_payload_projection *payload_projection,
    const artifact_archive_complete_workspace *workspace,
    artifact_archive_complete_projection *out);

#endif /* ARTIFACT_ARCHIVE_H */
