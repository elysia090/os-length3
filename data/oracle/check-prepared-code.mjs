import assert from 'node:assert/strict';
import {PreparedCode} from '../../src/v2/web/prepared-code.mjs';
const code=Uint8Array.from([0,97,115,109,1,0,0,0,1,5,1,96,0,1,127,3,2,1,0,7,7,1,3,99,117,116,0,0,10,6,1,4,0,65,7,11]);
const first=new WebAssembly.Instance(new WebAssembly.Module(code)),second=new WebAssembly.Instance(new WebAssembly.Module(code));
const value=instance=>({instance,sourceBytes:3,instructions:1,binding:0,bytes:code.length});
const owner=new PreparedCode({maximumEntries:2,maximumBytes:code.length});
owner.put('epoch1/slot2/version1',value(first));owner.put('epoch1/slot3/version1',value(first));
assert.equal(owner.stats().uniqueEncodedBytes,code.length);assert.equal(owner.stats().bodies,1);
assert.equal(owner.get('epoch1/slot2/version1').instance,first);
assert.equal(owner.get('epoch1/slot2/version2'),null,'changed physical code cannot select old construction');
assert.equal(owner.get('epoch2/slot2/version1'),null,'reopened owner cannot select old construction');
owner.put('epoch1/slot4/version1',value(second));assert.equal(owner.stats().entries,1);
assert.equal(owner.get('epoch1/slot2/version1'),null);assert.equal(owner.stats().bodies,1);
assert.equal(owner.get('epoch1/slot4/version1').instance.exports.cut(),7);
const before=owner.stats();assert.throws(()=>owner.put('bad',{...value(second),instructions:4}),RangeError);
assert.deepEqual(owner.stats(),before);
assert.throws(()=>owner.put('epoch1/slot4/version1',{...value(second),binding:1}),/immutable/);
assert.deepEqual(owner.stats(),before);
const extentOwner=new PreparedCode({maximumEntries:1,maximumBytes:code.length+1});
extentOwner.put('one',value(first));const extentBefore=extentOwner.stats();
assert.throws(()=>extentOwner.put('two',{...value(first),bytes:code.length+1}),/inconsistent extent/);
assert.deepEqual(extentOwner.stats(),extentBefore,'rejected extent cannot evict a retained construction');
extentOwner.put('two',value(first));assert.equal(extentOwner.stats().uniqueEncodedBytes,code.length);
assert.equal(extentOwner.stats().entries,1);extentOwner.close();
owner.close();assert.equal(owner.stats().uniqueEncodedBytes,0);assert.throws(()=>owner.get('x'),/closed/);
console.log(JSON.stringify({status:'pass',scope:'bounded construction references, unique body accounting, exact epoch/revision identity, eviction/release; C stamp authority separately checked'}));
