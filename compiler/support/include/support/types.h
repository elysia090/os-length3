/* Freestanding fixed-width scalar types shared by every v2 product. */

#ifndef SUPPORT_TYPES_H
#define SUPPORT_TYPES_H

typedef unsigned char      pl_u8;
typedef unsigned short     pl_u16;
typedef unsigned int       pl_u32;
typedef unsigned long long pl_u64;
typedef signed char        pl_i8;
typedef signed short       pl_i16;
typedef signed int         pl_i32;
typedef signed long long   pl_i64;

#endif /* SUPPORT_TYPES_H */
