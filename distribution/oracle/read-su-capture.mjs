import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const [log,out]=process.argv.slice(2);
if(!out)throw new Error('LOG NEW-ELF-OUTPUT');
const text=readFileSync(log,'utf8').replaceAll('\r','');
const start=text.lastIndexOf('su-capture-elf-begin\n'),end=text.indexOf('su-capture-elf-end',start);
if(start<0||end<start)throw new Error('complete capture required');
const lines=text.slice(start+'su-capture-elf-begin\n'.length,end).trim().split('\n');
const identity=/^([a-f0-9]{64})  \/usr\/bin\/su$/.exec(lines.shift());
if(!identity||lines.some(x=>!/^[A-Za-z0-9+/=]+$/.test(x)))throw new Error('canonical capture rows');
const bytes=Buffer.from(lines.join(''),'base64');
if(bytes.subarray(0,4).toString('hex')!=='7f454c46'||createHash('sha256').update(bytes).digest('hex')!==identity[1])throw new Error('ELF capture identity mismatch');
writeFileSync(out,bytes,{flag:'wx'});
console.log(JSON.stringify({bytes:bytes.length,sha256:identity[1],file:out,scope:'captured shipped native red, not a repaired product'}));
