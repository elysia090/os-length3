//! `l3 plan` as a person and a script meet it: a repo's steps in order, the same every run, said in English and in
//! Japanese, as data; an issue's likely place and what to read first; and what it says when there is nothing to plan,
//! no history, or no such repo. (Its repos' histories are made with sh and git, as on a Unix.)
#![cfg(unix)]

mod common;
use common::Home;
use std::process::Command;

/// A function far over the threshold, `depth` ifs deep.
fn tangled(name: &str, depth: usize) -> String {
    let mut s = format!("int {name}(int a) {{\n");
    for d in 0..depth { s.push_str(&format!("{}if (a > {d}) {{\n", "  ".repeat(d + 1))); }
    s.push_str(&format!("{}return a;\n", "  ".repeat(depth + 1)));
    for d in (0..depth).rev() { s.push_str(&format!("{}}}\n", "  ".repeat(d + 1))); }
    s.push_str("  return 0;\n}\n");
    s
}

/// `cmd` run with sh in the repo `name` of `home`, as git's author.
fn sh(home: &Home, name: &str, cmd: &str) {
    let ok = Command::new("sh").arg("-c").arg(cmd).current_dir(home.path(&format!("repos/{name}")))
        .env("GIT_AUTHOR_NAME", "a").env("GIT_AUTHOR_EMAIL", "a@b").env("GIT_COMMITTER_NAME", "a").env("GIT_COMMITTER_EMAIL", "a@b")
        .env("GIT_CONFIG_GLOBAL", "/dev/null").env("GIT_CONFIG_NOSYSTEM", "1").status().expect("sh").success();
    assert!(ok, "{cmd}");
}

/// A repo `calc` with two tangled functions and a history: the hot one changed in most commits.
fn calc(home: &Home) {
    home.repo("calc", &[
        ("src/hot.c", &tangled("hot", 7)),
        ("src/cold.c", &tangled("cold", 6)),
        ("src/ok.c", "int ok(int a) { return a + 1; }\n"),
        ("Makefile", "test:\n\t./run-tests\n"),
    ]);
    sh(home, "calc", "git init -q . && git add -A && git commit -qm start");
    for i in 0..30 {
        let f = if i % 4 == 3 { "src/cold.c" } else { "src/hot.c" };
        sh(home, "calc", &format!("echo '/* {i} */' >> {f} && git commit -qam 'Change {i}'"));
    }
}

#[test]
fn a_repos_steps_soonest_paid_back_first_the_same_every_run() {
    let home = Home::new("plan-steps");
    calc(&home);
    let first = home.run("en", &["plan", "calc"]);
    assert_eq!(first.code, 0, "{}", first.stderr);
    let out = &first.stdout;
    assert!(out.starts_with("calc: 2 steps, the soonest to pay back first."), "{out}");
    let hot = out.find("1. Rewrite hot() in src/hot.c:1-18").unwrap_or_else(|| panic!("hot first:\n{out}"));
    let cold = out.find("2. Rewrite cold() in src/cold.c:1-16").unwrap_or_else(|| panic!("cold second:\n{out}"));
    assert!(hot < cold);
    assert!(out.contains("complexity 28 (over 15 by 13)"), "{out}");
    assert!(out.contains("done when it is at most 15 and the tests pass"), "{out}");
    assert!(out.contains("Read 4 files (") && out.contains("and 31 commits"), "{out}");
    // No line wider than a terminal's hundred columns but the step headings, which name a place in full.
    for l in out.lines().filter(|l| !l.starts_with(|c: char| c.is_ascii_digit())) { assert!(l.chars().count() <= 160, "{l}"); }
    // Again: the same, byte for byte (no clock, no order a hash map gives).
    assert_eq!(home.run("en", &["plan", "calc"]), first);
    // As data: every fact the text says, and what each step is done when.
    let json = home.run("en", &["plan", "calc", "--json"]);
    let v: serde_json::Value = serde_json::from_str(&json.stdout).expect("JSON");
    assert_eq!(v["repo"], "calc");
    assert_eq!(v["steps"][0]["kind"], "rewrite");
    assert_eq!(v["steps"][0]["at"][0]["name"], "hot");
    assert_eq!(v["steps"][0]["done"][0]["check"], "atMost");
    assert_eq!(v["steps"][0]["done"][0]["most"], 15);
    assert_eq!(v["steps"][0]["facts"]["complexity"], 28);
    assert!(v["steps"][0]["payback"].as_f64().unwrap() < v["steps"][1]["payback"].as_f64().unwrap());
    assert_eq!(v["summary"]["commits"], 31);
    assert_eq!(v["history"], true);
}

#[test]
fn in_japanese() {
    let home = Home::new("plan-ja");
    calc(&home);
    let ja = home.run("ja", &["plan", "calc"]);
    assert_eq!(ja.code, 0, "{}", ja.stderr);
    assert!(ja.stdout.starts_with("calc：2件の手順（早く元が取れる順）。"), "{}", ja.stdout);
    assert!(ja.stdout.contains("1. hot() を書き直す（src/hot.c:1-18）"), "{}", ja.stdout);
    assert!(ja.stdout.contains("複雑さ 28（15 を 13 超える）"), "{}", ja.stdout);
}

#[test]
fn nothing_to_plan_no_history_and_no_such_repo() {
    let home = Home::new("plan-edges");
    // Clean code, and a binary and a generated file it never reads as code.
    home.repo("clean", &[("a.c", "int a(void) { return 1; }\n"), ("gen.c", "/* Generated by hand-me-down 1.0. DO NOT EDIT. */\nint g(void) { if (1) { if (2) { if (3) { if (4) { if (5) { if (6) {} } } } } } }\n")]);
    std::fs::write(home.path("repos/clean/logo.png"), b"\x89PNG\r\n\x1a\n\0\0\0").unwrap();
    let r = home.run("en", &["plan", "clean"]);
    assert_eq!(r.code, 0, "{}", r.stderr);
    assert!(r.stdout.starts_with("clean: no debt the plan can see that costs anything"), "{}", r.stdout);
    assert!(r.stdout.contains("no history here (not a git repository): every file is taken to change as often"), "{}", r.stdout);
    // Not a git repository, tangled: still a plan, every file taken to change alike.
    home.repo("flat", &[("x.c", &tangled("x", 8))]);
    let r = home.run("en", &["plan", "flat"]);
    assert!(r.stdout.starts_with("flat: 1 step,"), "{}", r.stdout);
    // An empty repo: nothing to read, nothing to say but that.
    std::fs::create_dir_all(home.path("repos/empty")).unwrap();
    let r = home.run("en", &["plan", "empty"]);
    assert_eq!(r.code, 0, "{}", r.stderr);
    assert!(r.stdout.contains("Read 0 files"), "{}", r.stdout);
    // No such repo: said so, and failing as a missing thing fails.
    let r = home.run("en", &["plan", "nope"]);
    assert_ne!(r.code, 0);
    assert!(r.stderr.contains("nope"), "{}", r.stderr);
}

#[test]
fn an_issues_likely_place_and_what_to_read_first() {
    let home = Home::new("plan-issue");
    home.repo("feet", &[
        ("feet.c", "#include \"feet.h\"\nint inches(double feet) {\n  return (int)(feet * 12);\n}\nint yards(double feet) {\n  return (int)(feet / 3);\n}\n"),
        ("feet.h", "int inches(double feet);\nint yards(double feet);\n"),
        ("print.c", "#include <stdio.h>\nvoid show(int n) { printf(\"%d\\n\", n); }\n"),
        ("Makefile", "test:\n\t./test-feet\n"),
        ("issue/001.md", "Fix：Inches round down\n\ninches(7.3) gives 87; it should be 88.\n"),
    ]);
    let r = home.run("en", &["plan", "feet#1"]);
    assert_eq!(r.code, 0, "{}", r.stderr);
    let lines: Vec<&str> = r.stdout.lines().collect();
    assert_eq!(lines[0], "feet#1 Fix：Inches round down");
    assert_eq!(lines[1], "Where its fix likely goes");
    assert!(lines[2].ends_with("feet.c:2-4 inches()"), "{}", r.stdout);
    assert!(r.stdout.contains("1. Write a test that fails because of #1 (make test)"), "{}", r.stdout);
    assert!(r.stdout.contains("Too few past fixes here to check this against: by the issue's words alone"), "{}", r.stdout);
    let v: serde_json::Value = serde_json::from_str(&home.run("en", &["plan", "feet#1", "--json"]).stdout).expect("JSON");
    assert_eq!(v["places"][0]["path"], "feet.c");
    assert_eq!(v["places"][0]["function"], "inches");
    assert_eq!(v["tests"], "make test");
    // The issue files are issues, never code to plan.
    let debt: serde_json::Value = serde_json::from_str(&home.run("en", &["plan", "feet", "--json"]).stdout).expect("JSON");
    assert_eq!(debt["summary"]["files"], 4);
}
