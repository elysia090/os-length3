import {PGlite} from '@electric-sql/pglite';
import {drizzle} from 'drizzle-orm/pglite';
import {migrate} from 'drizzle-orm/pglite/migrator';
import {MIGRATIONS} from '/home/user/libqm-prototype/os/service/neon.ts';
import * as schema from '/home/user/libqm-prototype/os/service/schema.ts';
let t = performance.now();
const pg = new PGlite(); await pg.waitReady; console.log('boot', Math.round(performance.now() - t)); t = performance.now();
await migrate(drizzle(pg, {schema}), {migrationsFolder: MIGRATIONS}); console.log('migrate', Math.round(performance.now() - t)); t = performance.now();
const dump = await pg.dumpDataDir('none'); console.log('dump', Math.round(performance.now() - t), dump.size); await pg.close();
