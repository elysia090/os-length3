    /// pointed. Measured two ways: the share caught by the top fifth of the files, and by the top-ranked files that
    /// hold a fifth of the lines (what reading them costs: a ranking that only points at big files does not win it).
    #[test]
    #[ignore]
    fn backtest() {
        let Some(dir) = std::env::var_os("PLAN_DIR").map(std::path::PathBuf::from) else { return };
        const SPLIT: usize = 300;
        let git = |args: &[&str], input: Option<&[u8]>| -> Vec<u8> {
            use std::io::Write;
            let mut c = std::process::Command::new("git");
            c.arg("-C").arg(&dir).args(args).env("GIT_NO_LAZY_FETCH", "1").stdout(std::process::Stdio::piped()).stderr(std::process::Stdio::null());
            if input.is_some() { c.stdin(std::process::Stdio::piped()); }
            let mut child = c.spawn().unwrap();
            if let Some(i) = input { let mut sin = child.stdin.take().unwrap(); let i = i.to_vec(); std::thread::spawn(move || { let _ = sin.write_all(&i); }); }
            child.wait_with_output().unwrap().stdout
        };
        let ids = String::from_utf8(git(&["log", "--no-merges", "--format=%H", "-n", &(SPLIT + 1).to_string()], None)).unwrap();
        let split = ids.lines().last().unwrap().to_string();
        // The files at the split, read whole from git's objects.
        let listed = git(&["ls-tree", "-r", "-z", "--name-only", &split], None);
        let paths: Vec<String> = listed.split(|&b| b == 0).filter(|p| !p.is_empty()).map(|p| String::from_utf8_lossy(p).into_owned())
            .filter(|p| !left_out(p, false) && !vendored(p)).collect();
        let request: Vec<u8> = paths.iter().flat_map(|p| format!("{split}:{p}\n").into_bytes()).collect();
        let batch = git(&["cat-file", "--batch"], Some(&request));
        let mut texts = Vec::new();
        let mut at = 0;
        for p in &paths {
            let nl = at + batch[at..].iter().position(|&b| b == b'\n').unwrap();
            let head = String::from_utf8_lossy(&batch[at..nl]).into_owned();
            at = nl + 1;
            let Some(size) = head.split(' ').nth(2).and_then(|n| n.parse::<usize>().ok()) else { continue };
            let bytes = batch[at..at + size].to_vec();
            at += size + 1;
            if bytes.len() as u64 <= LARGEST && written_by_hand(p, &bytes) { texts.push(Text { path: p.clone(), bytes }); }
        }
        let snap = Snapshot { texts, set_aside: 0, git: true };
        let index: HashMap<&str, usize> = snap.texts.iter().enumerate().map(|(i, t)| (t.path.as_str(), i)).collect();
        let fmt = "--format=%x01%H %ct %s";
        let before = past::parse(&git(&["log", "--no-merges", "-M", "--name-status", "-z", "-n", "2000", fmt, &split], None), &index);
        let after = past::parse(&git(&["log", "--no-merges", "-M", "--name-status", "-z", fmt, &format!("{split}..HEAD")], None), &index);
        let a = analyze(&snap, before);
        let p = debt::plan(&a);
        let n = a.files.len();
        let code: Vec<usize> = (0..n).filter(|&f| a.files[f].lang.is_some()).collect();
        // Each file's debt: the plan's steps' costs, a circle's spread over its files by how often each changes.
        let mut debt_of = vec![0.0; n];
        for st in p.steps.iter().chain(&p.kept) {
            let ids: Vec<usize> = st.at.iter().filter_map(|x| index.get(x.path.as_str()).copied()).collect();
            let total: f64 = ids.iter().map(|&f| a.rates.change[f]).sum::<f64>().max(1e-12);
            for &f in &ids { debt_of[f] += st.cost * if st.kind == debt::Kind::Untangle { a.rates.change[f] / total } else { 1.0 / ids.len() as f64 }; }
        }
        let complexity: Vec<f64> = (0..n).map(|f| a.files[f].funcs.iter().map(|g| g.complexity as f64).sum()).collect();
        let lines: Vec<f64> = (0..n).map(|f| a.files[f].lines as f64).collect();
        let scores: [(&str, Vec<f64>); 5] = [
            ("plan's debt", debt_of),
            ("hotspot (churn × complexity)", (0..n).map(|f| a.rates.change[f] * complexity[f]).collect()),
            ("churn", a.rates.change.clone()),
            ("complexity", complexity.clone()),
            ("lines", lines.clone()),
        ];
        let mut fixes = vec![0.0; n];
        let mut changes = vec![0.0; n];
        for c in &after.commits { for &f in &c.files { changes[f] += 1.0; if c.fix { fixes[f] += 1.0; } } }
        let total_lines: f64 = code.iter().map(|&f| lines[f]).sum();
        println!("{}: {} code files at the split, {} commits after ({} fixes)", dir.display(), code.len(), after.commits.len(), after.commits.iter().filter(|c| c.fix).count());
        println!("{:<30} {:>14} {:>14} {:>16} {:>16}", "ranked by", "fixes top 20%", "changes 20%", "fixes 20% lines", "changes 20% lines");
        for (name, score) in &scores {
            let mut order = code.clone();
            order.sort_by(|&x, &y| score[y].total_cmp(&score[x]).then(x.cmp(&y)));
            let caught = |outcome: &[f64], by_lines: bool| {
                let all: f64 = code.iter().map(|&f| outcome[f]).sum::<f64>().max(1e-12);
                let mut got = 0.0;
                let mut read = 0.0;
                for (i, &f) in order.iter().enumerate() {
                    if by_lines { if read + lines[f] > 0.2 * total_lines { break; } read += lines[f]; } else if i >= code.len() / 5 { break; }
                    got += outcome[f];
                }
                100.0 * got / all
            };
            println!("{:<30} {:>13.0}% {:>13.0}% {:>15.0}% {:>15.0}%", name, caught(&fixes, false), caught(&changes, false), caught(&fixes, true), caught(&changes, true));
        }
    }

    #[test]
    fn the_same_repo_the_same_analysis_whatever_the_threads_see() {
        let files: Vec<(String, String)> = (0..40).map(|i| (format!("src/m{i}.rs"), format!("use crate::m{}::x;\nfn f{i}(a: u8) {{ if a > {i} {{ for _ in 0..a {{ if a % 2 == 0 {{ g() }} }} }} }}\n", (i + 1) % 40))).collect();
        let mut with_lib: Vec<(&str, &str)> = files.iter().map(|(p, s)| (p.as_str(), s.as_str())).collect();
        let lib = (0..40).map(|i| format!("mod m{i};\n")).collect::<String>();
        with_lib.push(("src/lib.rs", &lib));
        let a = analyze(&texts(&with_lib), past::History::default());
        let b = analyze(&texts(&with_lib), past::History::default());
        assert_eq!(a.files.iter().map(|f| (&f.path, f.funcs.clone())).collect::<Vec<_>>(), b.files.iter().map(|f| (&f.path, f.funcs.clone())).collect::<Vec<_>>());
        assert_eq!(a.graph.edges, b.graph.edges);
        // m0 → m1 → … → m39 → m0: one circle of forty.
        assert_eq!(a.circles.len(), 1);
        assert_eq!(a.circles[0].len(), 40);
        assert_eq!(a.files[0].funcs[0].complexity, 1 + 2 + 3);
    }
