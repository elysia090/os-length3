//! The plan: what in a repo is hardest to work in and most worked in, what to do about it first, and where an
//! issue's fix most likely goes. Read-only: the repo is read (its files, its git history, offline), never written.
//!
//! The pieces, each a module with its own checks: code as tokens (lex), its functions and how hard each is to follow
//! (shape), which files use which and the circles among them (graph), code written twice (dup), what the history
//! says (past), what each of those costs and what to do first (debt), and where an issue's fix goes (locate).
//!
//! Every answer is the same for the same repo: no clock, no randomness, nothing taken in an order a hash map gives.

