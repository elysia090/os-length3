/// A file of the repo as the plan reads it: its text (none for one it set aside).
pub struct Text { pub path: String, pub bytes: Vec<u8> }

/// The repo's files as they are now, and those set aside (binary, generated, too large, a lock file).
#[derive(Default)]
pub struct Snapshot {
    pub texts: Vec<Text>,
    pub set_aside: u32,
    /// Whether it came from git (its files those git tracks or would track).
    pub git: bool,
}

/// Files larger than this are data, not code someone reads.
const LARGEST: u64 = 1 << 20;

/// Lock files: written by tools, never by hand.
const LOCKS: [&str; 10] = ["Cargo.lock", "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock", "go.sum", "composer.lock", "Gemfile.lock", "bun.lockb", "uv.lock"];

/// What the plan never reads as the repo's code: git's own folder, installed packages, build output, and the OS's
/// issues (read as issues, not code).
fn left_out(path: &str, walking: bool) -> bool {
    let mut parts = path.split('/');
    let first = parts.clone().next().unwrap_or_default();
    if first == "issue" { return true; }
    let name = path.rsplit('/').next().unwrap_or(path);
    if LOCKS.contains(&name) { return true; }
    parts.any(|p| p == ".git" || walking && matches!(p, "node_modules" | "target" | "__pycache__" | ".venv" | "dist"))
}

/// Code another project wrote, kept here (GitHub's own list of where it is kept): its debt is not this repo's to pay.
fn vendored(path: &str) -> bool {
    path.split('/').rev().skip(1).any(|p| matches!(p, "vendor" | "vendored" | "third_party" | "third-party" | "thirdparty" | "3rdparty" | "deps" | "external" | "extern" | "node_modules" | "bower_components"))
}

/// Whether a file's text is one a person wrote: not binary (a NUL early on), not marked generated, not minified.
pub fn written_by_hand(path: &str, bytes: &[u8]) -> bool {
    let head = &bytes[..bytes.len().min(8000)];
    if head.contains(&0) { return false; }
    // A program's output says so at its top: a code file whose first lines say it was generated was.
    if Lang::of(path, bytes).is_some() {
        let top = String::from_utf8_lossy(&bytes[..bytes.len().min(2048)]).to_lowercase();
        if ["@generated", "do not edit", "code generated", "auto-generated", "autogenerated", "automatically generated", "generated by",
            "made by gnu bison", "a bison parser", "generated with"].iter().any(|m| top.contains(m)) { return false; }
    }
    if bytes.len() > 5000 && Lang::of(path, bytes).is_some() {
        let lines = bytes.iter().filter(|&&b| b == b'\n').count().max(1);
        if bytes.len() / lines > 200 { return false; }
    }
    true
}

fn git_command(dir: &Path) -> std::process::Command {
    let mut c = std::process::Command::new("git");
    c.arg("-C").arg(dir).args(["-c", "core.quotePath=false"])
        .env("GIT_OPTIONAL_LOCKS", "0").env("GIT_NO_LAZY_FETCH", "1").env("GIT_TERMINAL_PROMPT", "0")
        .stdin(std::process::Stdio::null()).stderr(std::process::Stdio::null());
    c
}

/// The repo at `dir` as it is now: in a git repository the files git tracks (and those it would: new, not ignored),
/// else every file under it, git's folder and build output aside.
pub fn snapshot(dir: &Path) -> Snapshot {
    let listed = dir.join(".git").exists().then(|| git_command(dir).args(["ls-files", "-z", "--cached", "--others", "--exclude-standard"]).output().ok()).flatten()
        .filter(|o| o.status.success());
    let (paths, git): (Vec<String>, bool) = match listed {
        Some(o) => {
            let mut p: Vec<String> = o.stdout.split(|&b| b == 0).filter(|p| !p.is_empty()).map(|p| String::from_utf8_lossy(p).into_owned()).collect();
            p.sort();
            p.dedup();
            (p, true)
        }
        None => (walk(dir), false),
    };
    let mut snap = Snapshot { git, ..Snapshot::default() };
    for path in paths {
        if left_out(&path, !git) { continue; }
        if vendored(&path) { snap.set_aside += 1; continue; }
        let at = dir.join(&path);
        // Only plain files inside the repo: a link is not followed out of it.
        let Ok(meta) = std::fs::symlink_metadata(&at) else { continue };
        if !meta.is_file() { continue; }
        if meta.len() > LARGEST { snap.set_aside += 1; continue; }
        let Ok(bytes) = std::fs::read(&at) else { continue };
        if !written_by_hand(&path, &bytes) { snap.set_aside += 1; continue; }
        snap.texts.push(Text { path, bytes });
    }
    snap
}

fn walk(dir: &Path) -> Vec<String> {
    let mut out = Vec::new();
    let mut todo = vec![String::new()];
    while let Some(rel) = todo.pop() {
        let Ok(entries) = std::fs::read_dir(dir.join(&rel)) else { continue };
        for e in entries.flatten() {
            let name = e.file_name().to_string_lossy().into_owned();
            let path = if rel.is_empty() { name } else { format!("{rel}/{name}") };
            let Ok(t) = e.file_type() else { continue };
            if t.is_dir() { if !left_out(&path, true) { todo.push(path); } } else if t.is_file() { out.push(path); }
        }
    }
    out.sort();
    out
}

/// One file as the plan sees it.
#[derive(Clone, Debug, Serialize)]
pub struct FileFacts {
    pub path: String,
    #[serde(skip)]
    pub lang: Option<Lang>,
    /// Lines of code (a token starts on them); for a file that is not code, its lines.
    pub lines: u32,
    pub funcs: Vec<Func>,
}

/// A copy, as lines: (file, first line, last line) twice.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
pub struct Copied { pub a: (usize, u32, u32), pub b: (usize, u32, u32), pub tokens: u32 }

/// Everything the plan knows of a repo.
pub struct Analysis {
    pub files: Vec<FileFacts>,
    pub graph: graph::Graph,
    /// How many files each reaches (itself among them).
    pub reach: Vec<u32>,
    /// The circles: components of more than one file, the largest first.
    pub circles: Vec<Vec<usize>>,
    pub copies: Vec<Copied>,
    pub history: past::History,
    pub rates: past::Rates,
    /// Each file's words (names in its code, words of its comments and strings), for finding an issue's place.
    pub words: Vec<Vec<(String, u32)>>,
    pub set_aside: u32,
}

/// A token as copies are compared (dup.rs): keywords and punctuation as themselves, names and literals each as one.
fn compared(tok: &[u8], k: K) -> u32 {
    match k {
        K::Num | K::Str => dup::LITERAL,
        K::Word if !KEYWORDS.contains(&tok) => dup::NAME,
        _ => tok.iter().fold(0x811C_9DC5u32, |h, &b| (h ^ b as u32).wrapping_mul(0x0100_0193)) | 0x8000_0000,
    }
}

const KEYWORDS: [&[u8]; 64] = [b"if", b"else", b"for", b"while", b"do", b"switch", b"case", b"default", b"break", b"continue", b"return",
    b"match", b"loop", b"fn", b"function", b"func", b"def", b"class", b"struct", b"enum", b"impl", b"trait", b"let", b"const", b"var",
    b"mut", b"pub", b"static", b"async", b"await", b"yield", b"try", b"catch", b"finally", b"throw", b"new", b"in", b"of", b"is", b"as",
    b"import", b"from", b"export", b"use", b"mod", b"interface", b"type", b"typeof", b"true", b"false", b"null", b"nil", b"None",
    b"self", b"this", b"super", b"and", b"or", b"not", b"lambda", b"with", b"elif", b"except", b"unsafe"];

/// What one file gives the analysis.
struct Read {
    facts: FileFacts,
    compared: Vec<u32>,
    written: Vec<u32>,
    tok_lines: Vec<u32>,
    words: Vec<(String, u32)>,
    lexed: Option<(Lang, lex::Lexed)>,
}

fn read_one(t: &Text, want_words: bool) -> Read {
    let lang = Lang::of(&t.path, &t.bytes);
    let mut counts: HashMap<String, u32> = HashMap::new();
    let mut count = |text: &str, n: u32| if want_words { for w in locate::words(text) { *counts.entry(w).or_insert(0) += n; } };
    // The path's own words count as the file's (an issue often names a part by its folder or file name).
    count(&t.path, 3);
    let Some(lang) = lang else {
        let lines = t.bytes.iter().filter(|&&b| b == b'\n').count() as u32;
        count(&String::from_utf8_lossy(&t.bytes), 1);
        return Read { facts: FileFacts { path: t.path.clone(), lang: None, lines, funcs: Vec::new() }, compared: Vec::new(), written: Vec::new(), tok_lines: Vec::new(), words: sorted(counts), lexed: None };
    };
    let lexed = lex::lex(&t.bytes, lang);
    let sh = shape::shape(&t.bytes, &lexed, lang);
    let mut compared_toks = Vec::with_capacity(lexed.toks.len());
    let mut written = Vec::with_capacity(lexed.toks.len());
    let mut tok_lines = Vec::with_capacity(lexed.toks.len());
    for tok in lexed.toks.iter().filter(|x| x.k != K::Nl) {
        let text = lexed.text(&t.bytes, tok);
        compared_toks.push(compared(text, tok.k));
        written.push(text.iter().fold(0x811C_9DC5u32, |h, &b| (h ^ b as u32).wrapping_mul(0x0100_0193)));
        tok_lines.push(tok.line);
        if tok.k == K::Word { count(&String::from_utf8_lossy(text), 1); }
    }
    for &(a, b) in &lexed.prose { count(&String::from_utf8_lossy(&t.bytes[a as usize..b as usize]), 1); }
    // A function's name is what the file is about: it counts more.
    for f in &sh.funcs { count(&f.name, 2); }
    Read {
        facts: FileFacts { path: t.path.clone(), lang: Some(lang), lines: sh.code_lines, funcs: sh.funcs },
        compared: compared_toks, written, tok_lines, words: sorted(counts), lexed: Some((lang, lexed)),
    }
}

fn sorted(m: HashMap<String, u32>) -> Vec<(String, u32)> {
    let mut v: Vec<(String, u32)> = m.into_iter().collect();
    v.sort_unstable();
    v
}

/// The repo analyzed: each file read (in parallel, the same answer whatever the order), its structure, its copies,
/// its history's rates.
pub fn analyze(snap: &Snapshot, history: past::History) -> Analysis { analyze_timed(snap, history, true, &mut |_| {}) }

/// `analyze`, the files' words (what finding an issue's place needs) only if `words`, saying when each part is done
/// (`done(part)`): how its time is measured (E10).
pub fn analyze_timed(snap: &Snapshot, history: past::History, words: bool, done: &mut dyn FnMut(&'static str)) -> Analysis {
    let n = snap.texts.len();
    let threads = std::thread::available_parallelism().map_or(1, |p| p.get()).clamp(1, 16);
    let chunk = n.div_ceil(threads).max(1);
    let mut reads: Vec<Read> = Vec::with_capacity(n);
    std::thread::scope(|s| {
        let handles: Vec<_> = snap.texts.chunks(chunk).map(|part| s.spawn(move || part.iter().map(|t| read_one(t, words)).collect::<Vec<_>>())).collect();
        for h in handles { reads.extend(h.join().unwrap_or_default()); }
    });
    done("read");
    let all: Vec<(&str, &[u8])> = snap.texts.iter().map(|t| (t.path.as_str(), t.bytes.as_slice())).collect();
    let srcs: Vec<graph::Src> = reads.iter().zip(&snap.texts).filter_map(|(r, t)| r.lexed.as_ref().map(|(lang, lx)| graph::Src { path: &t.path, lang: *lang, src: &t.bytes, toks: &lx.toks })).collect();
    let g = graph::build(&srcs, &all);
    done("graph");
    let adj = g.adjacency();
    let reach = graph::reach(&adj);
    let mut circles: Vec<Vec<usize>> = graph::sccs(&adj).into_iter().filter(|c| c.len() > 1).collect();
    circles.sort_by(|a, b| b.len().cmp(&a.len()).then(a.cmp(b)));
    done("reach");
    let toks: Vec<dup::Tokens> = reads.iter_mut().map(|r| dup::Tokens { compared: std::mem::take(&mut r.compared), written: std::mem::take(&mut r.written) }).collect();
    let copies = dup::copies(&toks).into_iter().map(|c| {
        let line = |f: usize, i: u32| reads[f].tok_lines.get(i as usize).copied().unwrap_or(0);
        Copied { a: (c.a.0, line(c.a.0, c.a.1), line(c.a.0, c.a.2 - 1)), b: (c.b.0, line(c.b.0, c.b.1), line(c.b.0, c.b.2 - 1)), tokens: c.tokens() }
    }).collect();
    done("copies");
    let rates = past::rates(&history, n);
    let words = reads.iter_mut().map(|r| std::mem::take(&mut r.words)).collect();
    Analysis { files: reads.into_iter().map(|r| r.facts).collect(), graph: g, reach, circles, copies, history, rates, words, set_aside: snap.set_aside }
}

/// The repo at `dir` analyzed: its files now and (in a git repository) its history; the files' texts beside; their
/// words if `words`.
pub fn analyze_dir(dir: &Path, words: bool) -> (Snapshot, Analysis) {
    let snap = snapshot(dir);
    let index: HashMap<&str, usize> = snap.texts.iter().enumerate().map(|(i, t)| (t.path.as_str(), i)).collect();
    let history = past::from_git(dir, &index).unwrap_or_default();
    let a = analyze_timed(&snap, history, words, &mut |_| {});
    (snap, a)
}

